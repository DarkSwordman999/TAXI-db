-- Водители. Город публикует только обезличенный ID машины (taxi_id):
-- в Чикаго лицензия выдаётся на машину, поэтому водитель и машина
-- в данных неразличимы и одна запись описывает такси вместе с водителем.
CREATE TABLE ВОДИТЕЛИ (
    код SERIAL PRIMARY KEY,
    taxi_id VARCHAR(16) NOT NULL UNIQUE
);
