-- ЗАДАЧА 2: Распределение объема выручки по временам года И таксопаркам
SELECT 
    СЕЗОН.сезон AS "Время года",
    ТАКСОПАРКИ.название AS "Таксопарк",
    SUM(ПОЕЗДКИ.стоимость) AS "Выручка"
FROM ПОЕЗДКИ
INNER JOIN ТАКСОПАРКИ ON ТАКСОПАРКИ.код = ПОЕЗДКИ.таксопарк
INNER JOIN СЕЗОН ON СЕЗОН.месяц = EXTRACT(MONTH FROM ПОЕЗДКИ.дата)
GROUP BY СЕЗОН.сезон, СЕЗОН.порядок, ТАКСОПАРКИ.название
ORDER BY СЕЗОН.порядок, "Выручка" DESC;
