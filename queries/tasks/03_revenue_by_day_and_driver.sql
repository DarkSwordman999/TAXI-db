-- ЗАДАЧА 3: Распределение объема выручки по дням недели И водителям
-- День недели: 1 (понедельник) ... 7 (воскресенье).
-- Водителей тысячи, поэтому для каждого дня выводятся 5 с наибольшей выручкой.
SELECT "День недели", "Водитель", "Выручка"
FROM (
    SELECT 
        CAST(EXTRACT(ISODOW FROM ПОЕЗДКИ.дата) AS INTEGER) AS "День недели",
        'Водитель №' || ВОДИТЕЛИ.код AS "Водитель",
        SUM(ПОЕЗДКИ.стоимость) AS "Выручка",
        ROW_NUMBER() OVER (PARTITION BY EXTRACT(ISODOW FROM ПОЕЗДКИ.дата)
                           ORDER BY SUM(ПОЕЗДКИ.стоимость) DESC) AS место
    FROM ПОЕЗДКИ
    INNER JOIN ВОДИТЕЛИ ON ВОДИТЕЛИ.код = ПОЕЗДКИ.водитель
    GROUP BY EXTRACT(ISODOW FROM ПОЕЗДКИ.дата), ВОДИТЕЛИ.код
) AS по_дням
WHERE место <= 5
ORDER BY "День недели", "Выручка" DESC;
