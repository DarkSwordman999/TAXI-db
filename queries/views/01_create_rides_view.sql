DROP VIEW IF EXISTS v_rides_user;

-- Пользовательское представление: поездки с понятными названиями вместо кодов
CREATE VIEW v_rides_user AS
SELECT 
    П.код_поездки,
    П.дата,
    'Водитель №' || П.водитель AS водитель,
    Т.название AS таксопарк,
    К.описание AS оплата,
    РО.название AS откуда,
    РК.название AS куда,
    П.расстояние_км,
    П.время_мин,
    П.стоимость,
    П.чаевые
FROM ПОЕЗДКИ П
JOIN ТАКСОПАРКИ Т ON Т.код = П.таксопарк
JOIN КЛИЕНТЫ К ON К.код = П.клиент
LEFT JOIN РАЙОНЫ РО ON РО.код = П.откуда
LEFT JOIN РАЙОНЫ РК ON РК.код = П.куда;
