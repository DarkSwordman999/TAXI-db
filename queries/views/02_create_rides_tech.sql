DROP VIEW IF EXISTS v_rides_tech;

-- Технологическое представление: коды связей рядом с названиями и исходные ID города
CREATE VIEW v_rides_tech AS
SELECT 
    П.код_поездки,
    П.trip_id,
    П.дата,
    П.окончание,
    П.водитель AS водитель_код,
    В.taxi_id,
    П.таксопарк AS таксопарк_код,
    Т.название AS таксопарк,
    П.клиент AS клиент_код,
    К.тип AS тип_оплаты,
    П.откуда AS откуда_код,
    РО.название AS откуда,
    П.куда AS куда_код,
    РК.название AS куда,
    П.расстояние_км,
    П.время_мин,
    П.стоимость,
    П.чаевые,
    П.сборы
FROM ПОЕЗДКИ П
JOIN ВОДИТЕЛИ В ON В.код = П.водитель
JOIN ТАКСОПАРКИ Т ON Т.код = П.таксопарк
JOIN КЛИЕНТЫ К ON К.код = П.клиент
LEFT JOIN РАЙОНЫ РО ON РО.код = П.откуда
LEFT JOIN РАЙОНЫ РК ON РК.код = П.куда;
