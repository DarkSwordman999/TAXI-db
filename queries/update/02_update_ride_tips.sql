-- Корректировка чаевых и сборов поездки с кодом 1

BEGIN;

\echo '=== ДО UPDATE ==='
SELECT код_поездки, стоимость, чаевые, сборы FROM ПОЕЗДКИ WHERE код_поездки = 1;

UPDATE ПОЕЗДКИ 
SET (чаевые, сборы) = (чаевые + 2.00, сборы + 0.50) 
WHERE код_поездки = 1;

\echo '=== ПОСЛЕ UPDATE ==='
SELECT код_поездки, стоимость, чаевые, сборы FROM ПОЕЗДКИ WHERE код_поездки = 1;

-- Демонстрация: изменения откатываются, чтобы повторный запуск
-- не портил базу. Чтобы сохранить их, замените ROLLBACK на COMMIT.
ROLLBACK;
