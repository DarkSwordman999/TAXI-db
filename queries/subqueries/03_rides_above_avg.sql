\echo '=== ПОЕЗДКИ ДОРОЖЕ СРЕДНЕГО ПО ТАКСОПАРКУ (последний день) ==='

-- Средние по таксопаркам считает подзапрос в роли таблицы — один раз,
-- а не для каждой поездки
SELECT 
    П.код_поездки,
    Т.название AS таксопарк,
    П.стоимость,
    ROUND(средние.средняя, 2) AS средняя_по_таксопарку
FROM ПОЕЗДКИ П
JOIN ТАКСОПАРКИ Т ON Т.код = П.таксопарк
JOIN (
    SELECT таксопарк, AVG(стоимость) AS средняя
    FROM ПОЕЗДКИ
    GROUP BY таксопарк
) AS средние ON средние.таксопарк = П.таксопарк
WHERE П.стоимость > средние.средняя
  AND П.дата >= (SELECT MAX(дата)::date FROM ПОЕЗДКИ)
ORDER BY Т.название, П.стоимость DESC
LIMIT 20;
