\echo '=== ОТКЛОНЕНИЕ СТОИМОСТИ ПОЕЗДКИ ОТ СРЕДНЕГО ПО ВОДИТЕЛЮ (поездки последнего дня) ==='

-- Подзапросы в SELECT считаются для каждой строки, поэтому внешний набор
-- ограничен последним днём данных: иначе это сотни тысяч подзапросов.
SELECT 
    П.код_поездки,
    'Водитель №' || В.код AS водитель,
    П.стоимость,
    ROUND((SELECT AVG(стоимость) FROM ПОЕЗДКИ WHERE водитель = В.код), 2) AS средний_по_водителю,
    ROUND(П.стоимость - (SELECT AVG(стоимость) FROM ПОЕЗДКИ WHERE водитель = В.код), 2) AS отклонение
FROM ПОЕЗДКИ П
JOIN ВОДИТЕЛИ В ON В.код = П.водитель
WHERE П.дата >= (SELECT MAX(дата)::date FROM ПОЕЗДКИ)
ORDER BY отклонение DESC
LIMIT 10;
