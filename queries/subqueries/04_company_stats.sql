\echo '=== СТАТИСТИКА ПО ТАКСОПАРКАМ ==='

SELECT 
    таксопарк,
    поездок,
    средняя_стоимость,
    общая_выручка
FROM (
    SELECT 
        Т.название AS таксопарк,
        COUNT(*) AS поездок,
        ROUND(AVG(П.стоимость), 2) AS средняя_стоимость,
        SUM(П.стоимость) AS общая_выручка
    FROM ПОЕЗДКИ П
    JOIN ТАКСОПАРКИ Т ON Т.код = П.таксопарк
    GROUP BY Т.название
) AS company_stats
ORDER BY общая_выручка DESC;
