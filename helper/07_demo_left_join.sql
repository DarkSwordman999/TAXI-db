-- ДЕМОНСТРАЦИЯ LEFT JOIN: районы и число поездок из них (включая районы без поездок)
SELECT 
    РАЙОНЫ.код,
    РАЙОНЫ.название AS район,
    COUNT(ПОЕЗДКИ.код_поездки) AS количество_поездок
FROM РАЙОНЫ
LEFT JOIN ПОЕЗДКИ ON РАЙОНЫ.код = ПОЕЗДКИ.откуда
GROUP BY РАЙОНЫ.код, РАЙОНЫ.название
ORDER BY количество_поездок DESC
LIMIT 10;
