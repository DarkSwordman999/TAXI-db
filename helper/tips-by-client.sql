-- ./help.sh tips-by-client — средние чаевые по типам клиентов
SELECT
    К.описание AS тип_клиента,
    ROUND(AVG(П.чаевые), 2) AS средние_чаевые,
    ROUND(100.0 * AVG(П.чаевые / П.стоимость), 1) AS процент_от_стоимости
FROM ПОЕЗДКИ П
JOIN КЛИЕНТЫ К ON К.код = П.клиент
GROUP BY К.описание
ORDER BY средние_чаевые DESC;
