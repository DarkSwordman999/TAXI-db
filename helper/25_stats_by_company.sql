-- Статистика по таксопаркам: водители, поездки, средний чек и чаевые
SELECT 
    Т.название AS таксопарк,
    COUNT(DISTINCT П.водитель) AS водителей,
    COUNT(*) AS поездок,
    ROUND(AVG(П.стоимость), 2) AS средний_чек,
    ROUND(AVG(П.чаевые), 2) AS средние_чаевые
FROM ПОЕЗДКИ П
JOIN ТАКСОПАРКИ Т ON Т.код = П.таксопарк
GROUP BY Т.название
ORDER BY поездок DESC;
