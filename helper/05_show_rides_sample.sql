-- Показать 10 последних поездок
SELECT 
    ПОЕЗДКИ.код_поездки,
    'Водитель №' || ВОДИТЕЛИ.код AS водитель,
    ТАКСОПАРКИ.название AS таксопарк,
    ПОЕЗДКИ.расстояние_км,
    ПОЕЗДКИ.стоимость,
    ПОЕЗДКИ.дата
FROM ПОЕЗДКИ
INNER JOIN ВОДИТЕЛИ ON ВОДИТЕЛИ.код = ПОЕЗДКИ.водитель
INNER JOIN ТАКСОПАРКИ ON ТАКСОПАРКИ.код = ПОЕЗДКИ.таксопарк
ORDER BY ПОЕЗДКИ.дата DESC
LIMIT 10;
