-- ./help.sh join-self — SELF JOIN
SELECT
    Р1.название AS район,
    Р2.название AS соседний_к_северу,
    ROUND(Р2.широта - Р1.широта, 3) AS разница_широт
FROM РАЙОНЫ Р1
JOIN РАЙОНЫ Р2
  ON Р2.широта > Р1.широта
 AND Р2.широта - Р1.широта < 0.02
 AND ABS(Р2.долгота - Р1.долгота) < 0.02
 AND Р1.код != Р2.код
ORDER BY Р1.название
LIMIT 10;
