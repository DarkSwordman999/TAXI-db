-- ./help.sh drivers-above сумма — водители с выручкой выше суммы
-- параметры: :arg1 — сумма (help.sh задает их через \set, psql сам экранирует кавычки)
SELECT
    'Водитель №' || В.код AS водитель,
    SUM(П.стоимость) AS выручка
FROM ВОДИТЕЛИ В
JOIN ПОЕЗДКИ П ON В.код = П.водитель
GROUP BY В.код
HAVING SUM(П.стоимость) > :arg1
ORDER BY выручка DESC;
